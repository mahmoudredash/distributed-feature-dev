#!/usr/bin/env python3
"""
orch.py v2 - helper for the distributed-feature-dev skill.

Runs on the MANAGER machine from the project repo root. State: .orch/state.json.
Workers are reached over SSH. Each task runs in its own git worktree on the
worker, so one machine can run several agents at once (slots), sized from the
machine's real CPU / RAM / load.

Workflow commands
  doctor                                   check every worker (ssh, git, tmux, agents, repo access)
  capacity                                 probe CPU/RAM/load and show free slots per worker
  init      --feature NAME [--base main]   create feature branch + state
  local     --task ID                      start the manager's own task branch
  dispatch  --task ID --worker W [--agent A] [--model M] [--role R] --prompt-file F
  qa        --task ID --worker W [--agent A] [--model M] --prompt-file F   independent read-only QA
  status                                   refresh + print all tasks
  wait      [--interval 60] [--timeout 0]  block until something finishes
  log       --task ID [--what run|agent|verify] [-n 80]
  report    --task QA-ID                   print a QA report
  review    --task ID [--full] [--worktree] [--verify]
  accept    --task ID [--force]            merge into feature branch, clean worker worktree
  reject    --task ID --issue KEY --prompt-file F [--agent A] [--model M] [--worker W]
  takeover  --task ID                      stop worker, check branch out locally
  clear-quota --worker W --agent A [--model M]   mark an agent/model usable again
  summary                                  overview + metrics

Exit codes: 0 ok, 1 error, 2 merge conflict, 3 TAKEOVER required, 4 no free slot.
"""
import argparse
import fnmatch
import json
import os
import re
import shlex
import signal
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

STATE_DIR = Path(".orch")
STATE = STATE_DIR / "state.json"
CONFIG_PATHS = [STATE_DIR / "config.json", Path.home() / ".config" / "orch" / "config.json"]
ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,40}$")

# --------------------------------------------------------------------------- remote scripts
RUNNER = r'''#!/usr/bin/env bash
# Generated by orch.py - runs ONE task on this worker. Do not edit by hand.
set -u
for f in "$HOME/.profile" "$HOME/.bashrc"; do [ -f "$f" ] && . "$f" >/dev/null 2>&1; done
TASK=@@TASK@@
KIND=@@KIND@@
REPO=@@REPO@@
URL=@@URL@@
BRANCH=@@BRANCH@@
START_FROM=@@START_FROM@@
VERIFY=@@VERIFY@@
TIMEOUT_MIN=@@TIMEOUT_MIN@@
SELF_FIX=@@SELF_FIX@@
QUOTA_RE=@@QUOTA_RE@@
DIR="$HOME/.orch"
WT="$REPO.wt/$TASK"
STATUS="$DIR/$TASK.status"
LOG="$DIR/$TASK.log"
ALOG="$DIR/$TASK.agent.log"
VLOG="$DIR/$TASK.verify.log"
echo running > "$STATUS"
date +%s > "$DIR/$TASK.started"
touch "$ALOG"
exec >>"$LOG" 2>&1
say()  { echo "[$(date +%H:%M:%S)] $*"; }
fail() { echo "failed: $1" > "$STATUS"; say "FAILED: $1"; exit 1; }
TO=""
if [ "$TIMEOUT_MIN" -le 0 ]; then :
elif command -v timeout >/dev/null 2>&1; then TO="timeout --kill-after=60 ${TIMEOUT_MIN}m"
elif command -v gtimeout >/dev/null 2>&1; then TO="gtimeout --kill-after=60 ${TIMEOUT_MIN}m"; fi
lock()   { if command -v flock >/dev/null 2>&1; then exec 9>"$REPO.lock"; flock 9; fi; }
unlock() { if command -v flock >/dev/null 2>&1; then flock -u 9; fi; }

say "=== start $TASK ($KIND) on $BRANCH"
# ---- workspace: one shared clone per worker, one worktree per task
mkdir -p "$(dirname "$REPO")" "$REPO.wt"
lock
if [ ! -d "$REPO/.git" ]; then git clone -q "$URL" "$REPO" || { unlock; fail clone; }; fi
git -C "$REPO" fetch -q origin --prune || { unlock; fail fetch; }
git -C "$REPO" worktree prune
if [ "$KIND" = qa ] || git -C "$REPO" rev-parse -q --verify "origin/$BRANCH" >/dev/null; then
  REF="origin/$BRANCH"; else REF="origin/$START_FROM"; fi
if [ -d "$WT/.git" ] || [ -f "$WT/.git" ]; then
  git -C "$WT" reset -q --hard; git -C "$WT" clean -fdq
  if [ "$KIND" = qa ]; then git -C "$WT" checkout -q --detach "$REF"
  else git -C "$WT" checkout -q -B "$BRANCH" "$REF"; fi || { unlock; fail checkout; }
else
  rm -rf "$WT"
  if [ "$KIND" = qa ]; then git -C "$REPO" worktree add --detach "$WT" "$REF"
  else git -C "$REPO" worktree add -B "$BRANCH" "$WT" "$REF"; fi || { unlock; fail worktree; }
fi
unlock
cd "$WT" || fail cd

QUOTA_HIT=0
run_agent() {   # $1 = prompt file
  local start rc
  start=$(wc -l < "$ALOG")
  say "agent start: $(basename "$1")"
  $TO bash "$DIR/$TASK.agent.sh" "$1" >>"$ALOG" 2>&1 < /dev/null
  rc=$?
  say "agent exit $rc"
  if [ -n "$QUOTA_RE" ] && tail -n +"$((start + 1))" "$ALOG" | grep -Eiq "$QUOTA_RE"; then QUOTA_HIT=1; say "quota/rate limit detected"; fi
  for d in rebase-merge rebase-apply; do [ -d "$(git rev-parse --git-path $d)" ] && git rebase --abort; done
  return $rc
}
commit_all() { git add -A && { git diff --cached --quiet || git commit -q -m "$1"; }; }
run_verify() { [ -z "$VERIFY" ] && return 0; bash -c "$VERIFY" > "$VLOG" 2>&1; }

# ---- independent QA: read-only, nothing is committed
if [ "$KIND" = qa ]; then
  run_agent "$DIR/$TASK.prompt.md"; RC=$?
  if [ -f ORCH_QA_REPORT.md ]; then cp ORCH_QA_REPORT.md "$DIR/$TASK.report.md"
  else echo "(the QA agent wrote no ORCH_QA_REPORT.md)" > "$DIR/$TASK.report.md"; fi
  git reset -q --hard; git clean -fdq
  if [ -n "$VERIFY" ]; then if run_verify; then V=green; else V=red; fi; else V=none; fi
  if [ $QUOTA_HIT = 1 ]; then echo quota; elif [ $RC = 124 ] || [ $RC = 137 ]; then echo timeout
  else echo "done $V qa"; fi > "$STATUS"
  exit 0
fi

# ---- implementation
run_agent "$DIR/$TASK.prompt.md"; RC=$?
commit_all "[$TASK] agent work ($(hostname))" || fail commit
TIMED_OUT=0; { [ $RC = 124 ] || [ $RC = 137 ]; } && TIMED_OUT=1

# rebase onto the latest feature branch so the manager gets a clean merge
CONFLICT=0
if [ $QUOTA_HIT = 0 ] && [ $TIMED_OUT = 0 ]; then
  lock; git fetch -q origin; unlock
  if ! git merge-base --is-ancestor "origin/$START_FROM" HEAD; then
    if ! git rebase -q "origin/$START_FROM" >/dev/null 2>&1; then
      FILES=$(git diff --name-only --diff-filter=U | tr '\n' ' ')
      git rebase --abort
      cat > "$DIR/$TASK.conflict.md" <<EOF
# Rebase needed for task $TASK
Your branch \`$BRANCH\` conflicts with \`origin/$START_FROM\` (other agents' merged work).
For this step ONLY you are allowed to run git rebase and create commits.
1. git rebase origin/$START_FROM
2. Resolve the conflicts in: $FILES
   Keep the intent of BOTH sides: their side is already accepted; adapt your code to it.
3. git add the files and git rebase --continue until it finishes.
4. Make sure the project still builds.
EOF
      run_agent "$DIR/$TASK.conflict.md"
      commit_all "[$TASK] post-rebase fixes" || true
      git merge-base --is-ancestor "origin/$START_FROM" HEAD || CONFLICT=1
    fi
  fi
fi

# verify, with self-fix attempts on this machine before reporting
V=none
if [ -n "$VERIFY" ] && [ $QUOTA_HIT = 0 ] && [ $TIMED_OUT = 0 ] && [ $CONFLICT = 0 ]; then
  i=0
  while :; do
    say "verify (attempt $i)"
    if run_verify; then V=green; break; fi
    V=red
    [ "$i" -ge "$SELF_FIX" ] && break
    i=$((i + 1))
    { echo "# Self-fix $i for task $TASK: verification failed"
      echo
      echo "The project check \`$VERIFY\` fails on your branch. Find and fix the root cause."
      echo "Do not weaken, skip or delete tests. Stay inside the files your task owns. Do not commit."
      echo
      echo "Last 120 lines of output:"
      echo '```'; tail -n 120 "$VLOG"; echo '```'; } > "$DIR/$TASK.selffix.md"
    run_agent "$DIR/$TASK.selffix.md"
    commit_all "[$TASK] self-fix $i" || fail commit
    [ $QUOTA_HIT = 1 ] && break
  done
fi

# always push: partial work is the checkpoint for a handoff
git push -q --force-with-lease -u origin "$BRANCH" || fail push
SHA=$(git rev-parse --short HEAD)
if [ $QUOTA_HIT = 1 ]; then echo "quota $SHA"
elif [ $TIMED_OUT = 1 ]; then echo "timeout $SHA"
elif [ $CONFLICT = 1 ]; then echo "done conflict $SHA"
else echo "done $V $SHA"; fi > "$STATUS"
say "=== end: $(cat "$STATUS")"
'''

AGENT_SH = '''#!/usr/bin/env bash
# Generated by orch.py - one agent invocation. $1 = prompt file.
for f in "$HOME/.profile" "$HOME/.bashrc"; do [ -f "$f" ] && . "$f" >/dev/null 2>&1; done
PROMPT_FILE="$1"
@@CMD@@
'''

PROBE = r'''
echo "cpu=$(nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 1)"
if [ -r /proc/meminfo ]; then echo "mem_gb=$(awk '/MemAvailable/{printf "%.1f", $2/1048576}' /proc/meminfo)"
else echo "mem_gb=$(vm_stat 2>/dev/null | awk '/Pages free|Pages inactive/{s+=$NF} END{printf "%.1f", s*4096/1073741824}')"; fi
echo "load=$( (cut -d' ' -f1 /proc/loadavg) 2>/dev/null || sysctl -n vm.loadavg | awk '{print $2}')"
echo "disk_gb=$(df -Pk "$HOME" | awk 'NR==2{printf "%.0f", $4/1048576}')"
for c in git tmux timeout gtimeout flock node npx claude opencode agy; do command -v $c >/dev/null 2>&1 && echo "has_$c=1"; done
true
'''

