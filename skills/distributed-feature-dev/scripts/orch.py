def changed_files(base, ref):
    return [f for f in git("diff", "--name-only", f"{base}...{ref}").stdout.split() if f]


def cmd_review(a):
    cfg, st = load_config(), load_state()
    t = task_or_die(st, a.task)
    git("fetch", "origin", "--prune")
    fb, br = f"origin/{st['feature_branch']}", f"origin/{t['branch']}"
    if git("rev-parse", "--verify", br, check=False).returncode != 0:
        die(f"{br} does not exist - nothing was pushed")
    print(f"## worker result: {t.get('remote') or t['status']}")
    print("## commits\n" + git("log", "--oneline", f"{fb}..{br}").stdout)
    print("## files\n" + git("diff", "--stat", f"{fb}...{br}").stdout)
    files = changed_files(fb, br)
    hits = [f for f in files for p in cfg.get("protected_paths") or [] if fnmatch.fnmatch(f, p)]
    if hits:
        print("!! PROTECTED FILES CHANGED (contract tests?): " + ", ".join(sorted(set(hits))))
    if a.full:
        print("## diff\n" + git("diff", f"{fb}...{br}").stdout)
    if a.worktree or a.verify:
        wt = STATE_DIR / "wt" / a.task
        git("worktree", "remove", "--force", str(wt), check=False)
        git("worktree", "add", "--detach", str(wt), br)
        print(f"## worktree: {wt}")
        if a.verify and cfg.get("verify"):
            r = subprocess.run(["bash", "-c", cfg["verify"]], cwd=wt, text=True, capture_output=True)
            print(f"## local verify: {'GREEN' if r.returncode == 0 else 'RED'}")
            if r.returncode:
                print("\n".join((r.stdout + r.stderr).splitlines()[-60:]))


def cleanup_remote(cfg, st, tid):
    t = st["tasks"][tid]
    if t["worker"] in (None, "manager"):
        return
    w = get_worker(cfg, t["worker"])
    ssh(w, f"git -C {qpath(w['repo_path'])} worktree remove --force {wt_path(w, tid)} 2>/dev/null; "
           f"tmux kill-session -t orch-{tid} 2>/dev/null; true", check=False)


def cmd_accept(a):
    cfg, st = load_config(), load_state()
    t = task_or_die(st, a.task)
    if t["kind"] == "qa":
        die("accept the implementation task, not the QA task")
    if t["status"] not in ("done", "manager") and not a.force:
        die(f"task status is '{t['status']}'. Only finished ('done') or manager-owned tasks can be accepted (--force to override).")
    if t.get("result") in ("red", "conflict") and t["status"] != "manager" and not a.force:
        die(f"worker reported '{t['result']}'. Send a fix, take over, or --force if you verified it yourself.")
    if git("status", "--porcelain", "--untracked-files=no").stdout.strip():
        die("working tree has uncommitted changes; commit or stash first")
    fb = st["feature_branch"]
    git("fetch", "origin", "--prune")
    git("checkout", "-B", fb, f"origin/{fb}")
    r = git("merge", "--no-ff", f"origin/{t['branch']}", "-m", f"Merge {a.task} ({t['worker']}:{t['agent']}) into {fb}", check=False)
    if r.returncode != 0:
        git("merge", "--abort", check=False)
        print(r.stdout + r.stderr)
        print(f"CONFLICT merging {a.task}. Resolve it yourself if small, or `reject --issue merge-conflict` "
              f"(the worker's runner rebases automatically on the next round).")
        sys.exit(2)
    git("push", "origin", fb)
    t["status"] = "accepted"
    t["finished_at"] = t["finished_at"] or now()
    log_event(t, "accepted")
    for k, q in st["tasks"].items():
        if k == a.task or q.get("target") == a.task:
            cleanup_remote(cfg, st, k)
    git("worktree", "remove", "--force", str(STATE_DIR / "wt" / a.task), check=False)
    save_state(st)
    print(f"{a.task} merged into {fb} and pushed")


def cmd_reject(a):
    cfg, st = load_config(), load_state()
    t = task_or_die(st, a.task)
    if t["worker"] == "manager":
        die("this task belongs to the manager; fix it yourself")
    if t["status"] == ACTIVE:
        die("task is still running")
    if t["status"] == "accepted":
        die("task is already merged; open a new task (e.g. <id>-fix1) for follow-up work")
    key = a.issue.strip().lower()
    done = t["issues"].get(key, 0)
    lim, lim_total = st.get("max_fix_rounds", 3), st.get("max_total_rounds", 5)
    if done >= lim or t["rounds"] >= lim_total:
        why = f"issue '{key}' sent back {done} times (limit {lim})" if done >= lim else \
              f"{t['rounds']} fix rounds in total (limit {lim_total})"
        t["status"] = "manager"
        log_event(t, "takeover", issue=key, reason=why)
        save_state(st)
        print(f"TAKEOVER: {why}. Do NOT send it again. Run `orch.py takeover --task {a.task}` and fix it yourself.")
        sys.exit(3)
    if a.worker:
        t["worker"] = a.worker
    if a.agent:
        t["agent"] = a.agent
        t["model"] = None
    if a.model:
        t["model"] = a.model
    w = get_worker(cfg, t["worker"])
    preflight(cfg, st, w, t["agent"], a.force, t["model"])
    t["issues"][key] = done + 1
    t["rounds"] += 1
    launch(cfg, st, a.task, Path(a.prompt_file).read_text())
    log_event(t, "fix-round", issue=key, n=done + 1, prompt=a.prompt_file, where=f"{t['worker']}:{t['agent']}")
    save_state(st)
    print(f"fix round {done + 1}/{lim} for '{key}' (total {t['rounds']}/{lim_total}) -> {t['worker']}:{t['agent']}")


def cmd_takeover(a):
    cfg, st = load_config(), load_state()
    t = task_or_die(st, a.task)
    if t["worker"] not in (None, "manager"):
        ssh(get_worker(cfg, t["worker"]), f"tmux kill-session -t orch-{a.task} 2>/dev/null; "
            f"echo 'failed: taken over by manager' > ~/.orch/{a.task}.status", check=False)
    git("fetch", "origin")
    has_remote = git("rev-parse", "--verify", f"origin/{t['branch']}", check=False).returncode == 0
    git("checkout", "-B", t["branch"], f"origin/{t['branch']}" if has_remote else f"origin/{st['feature_branch']}")
    t["status"] = "manager"
    log_event(t, "takeover-checkout", previous=f"{t['worker']}:{t['agent']}")
    save_state(st)
    print(f"on {t['branch']}. Fix, commit, push, then `orch.py accept --task {a.task}`.")


def cmd_clear_quota(a):
    st = load_state()
    st["exhausted"].pop(qkey(a.worker, a.agent, a.model), None)
    save_state(st)
    print("cleared")


def cmd_summary(a):
    st = load_state()
    print_table(st)
    impl = {k: t for k, t in st["tasks"].items() if t["kind"] == "impl"}
    open_ = [k for k, t in impl.items() if t["status"] != "accepted"]
    print("\nALL TASKS ACCEPTED" if not open_ else f"\nnot accepted yet: {', '.join(open_)}")
    print("\n## metrics")
    per_agent = {}
    for k, t in impl.items():
        ag = t["agent"] or "?"
        d = per_agent.setdefault(ag, {"tasks": 0, "first_pass": 0, "rounds": 0, "takeovers": 0})
        d["tasks"] += 1
        d["rounds"] += t["rounds"]
        d["takeovers"] += any(h["event"] == "takeover" for h in t["history"])
        d["first_pass"] += t["status"] == "accepted" and t["rounds"] == 0
        dur = ""
        if t["started_at"] and t["finished_at"]:
            dur = f"{int((datetime.fromisoformat(t['finished_at']) - datetime.fromisoformat(t['started_at'])).total_seconds() // 60)}m"
        print(f"  {k:16} {t['worker']}:{ag:10} rounds={t['rounds']} {dur}")
    for ag, d in per_agent.items():
        print(f"  [{ag}] tasks={d['tasks']} accepted-first-time={d['first_pass']} fix-rounds={d['rounds']} takeovers={d['takeovers']}")


