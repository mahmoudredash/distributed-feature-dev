# --------------------------------------------------------------------------- helpers
def die(msg, code=1):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(code)


def run(cmd, check=True, inp=None, cwd=None):
    r = subprocess.run(cmd, text=True, capture_output=True, input=inp, cwd=cwd)
    if check and r.returncode != 0:
        die(f"command failed ({r.returncode}): {' '.join(cmd)}\n{r.stdout}{r.stderr}")
    return r


def git(*args, check=True):
    return run(["git", *args], check=check)


def now():
    return datetime.now().isoformat(timespec="seconds")


def load_config():
    for p in CONFIG_PATHS:
        if p.exists():
            cfg = json.loads(p.read_text())
            for w in cfg["workers"]:       # v1 compatibility: "agent": "x"
                if "agents" not in w:
                    w["agents"] = [w["agent"]] if w.get("agent") else []
            return cfg
    die("no config found. Copy config.example.json to .orch/config.json and fill it in.")


def load_state():
    if not STATE.exists():
        die("no state yet; run `orch.py init --feature NAME` first")
    st = json.loads(STATE.read_text())
    st.setdefault("exhausted", {})
    return st


def save_state(st):
    STATE_DIR.mkdir(exist_ok=True)
    tmp = STATE.with_suffix(".tmp")
    tmp.write_text(json.dumps(st, indent=2, ensure_ascii=False))
    tmp.replace(STATE)


def check_id(tid):
    if not ID_RE.match(tid):
        die(f"bad task id '{tid}': use letters, digits, - and _ only")


def get_worker(cfg, name):
    for w in cfg["workers"]:
        if w["name"] == name:
            return w
    die(f"unknown worker '{name}'. Known: {[w['name'] for w in cfg['workers']]}")


def ssh(w, remote_cmd, inp=None, check=True):
    cmd = ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=15"]
    if w.get("port"):
        cmd += ["-p", str(w["port"])]
    if w.get("identity_file"):
        cmd += ["-i", os.path.expanduser(w["identity_file"])]
    cmd += [f"{w['user']}@{w['host']}" if w.get("user") else w["host"], remote_cmd]
    return run(cmd, check=check, inp=inp)


def qpath(p):
    """Shell-quote a remote path but keep a leading ~ expandable."""
    if p == "~":
        return '"$HOME"'
    if p.startswith("~/"):
        return '"$HOME"/' + shlex.quote(p[2:])
    return shlex.quote(p)


def wt_path(w, tid):
    return qpath(w["repo_path"]) + shlex.quote(f".wt/{tid}")


def task_or_die(st, tid):
    t = st["tasks"].get(tid)
    if not t:
        die(f"unknown task '{tid}'")
    return t


def log_event(t, event, **kw):
    t["history"].append({"at": now(), "event": event, **kw})


def new_task(st, tid, **kw):
    t = {"kind": "impl", "worker": None, "agent": None, "model": None, "role": "implementer",
         "branch": f"{st['feature_branch']}--{tid}", "status": "pending", "result": None,
         "issues": {}, "rounds": 0, "history": [], "started_at": None, "finished_at": None}
    t.update(kw)
    st["tasks"][tid] = t
    return t


# --------------------------------------------------------------------------- capacity
def probe(w):
    r = ssh(w, PROBE, check=False)
    if r.returncode != 0:
        return None
    out = {}
    for line in r.stdout.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def capacity_of(cfg, st, w, pr):
    sc = cfg.get("slots", {})
    running = sum(1 for t in st["tasks"].values() if t["worker"] == w["name"] and t["status"] == ACTIVE)
    if pr is None:
        return {"running": running, "total": 0, "free": 0, "why": "unreachable"}
    ms = w.get("max_slots", "auto")
    if ms != "auto":
        total = int(ms)
        return {"running": running, "total": total, "free": max(0, total - running), "why": "fixed"}
    cpu = float(pr.get("cpu") or 1)
    mem = float(pr.get("mem_gb") or 0)
    load = float(pr.get("load") or 0)
    total = max(1, min(int(cpu // sc.get("cpu_per_slot", 2)), sc.get("max_per_worker", 4)))
    by_mem = int(mem // sc.get("mem_per_slot_gb", 3))
    free = min(total - running, by_mem)
    why = f"cpu {cpu:g}, free RAM {mem:g}GB, load {load:g}"
    if load > cpu * sc.get("max_load_ratio", 0.9):
        free, why = 0, why + " -> CPU pressure, queue work"
    elif by_mem < total - running:
        why += " -> limited by RAM"
    return {"running": running, "total": total, "free": max(0, free), "why": why}


# --------------------------------------------------------------------------- launching
def build_agent_cmd(cfg, agent, model):
    spec = cfg["agents"].get(agent)
    if spec is None:
        die(f"agent '{agent}' is not defined in config.agents")
    if isinstance(spec, str):
        spec = {"cmd": spec}
    flag = ""
    if model:
        if not spec.get("model_flag"):
            die(f"agent '{agent}' has no model_flag in config; cannot select model '{model}'")
        flag = spec["model_flag"].replace("{model}", shlex.quote(model))
    return spec["cmd"].replace("{prompt_file}", '"$PROMPT_FILE"').replace("{model_flag}", flag), spec


def launch(cfg, st, tid, body):
    t = st["tasks"][tid]
    w = get_worker(cfg, t["worker"])
    cmd, spec = build_agent_cmd(cfg, t["agent"], t.get("model"))
    url = w.get("repo_url") or cfg.get("repo_url") or git("remote", "get-url", "origin").stdout.strip()
    verify = cfg.get("verify", "")
    if t["kind"] == "qa":
        pre = QA_PREAMBLE.format(branch=t["branch"], target=t["target"])
    else:
        prot = cfg.get("protected_paths") or []
        prot_txt = ("\n- Protected paths (never modify): " + ", ".join(f"`{p}`" for p in prot)) if prot else ""
        pre = IMPL_PREAMBLE.format(branch=t["branch"], role=t.get("role", "implementer"), task=tid,
                                   protected=prot_txt, verify=verify or "the project's tests")
    vals = {
        "TASK": tid, "KIND": t["kind"], "URL": url, "BRANCH": t["branch"],
        "START_FROM": st["feature_branch"], "VERIFY": verify,
        "TIMEOUT_MIN": str(int(cfg.get("task_timeout_min", 45))),
        "SELF_FIX": str(int(cfg.get("self_fix_attempts", 2))),
        "QUOTA_RE": spec.get("quota_patterns", ""),
    }
    script = RUNNER.replace("@@REPO@@", qpath(w["repo_path"]))
    for k, v in vals.items():
        script = script.replace(f"@@{k}@@", shlex.quote(v))
    ssh(w, f"mkdir -p ~/.orch && cat > ~/.orch/{tid}.sh", inp=script)
    ssh(w, f"cat > ~/.orch/{tid}.agent.sh", inp=AGENT_SH.replace("@@CMD@@", cmd))
    ssh(w, f"cat > ~/.orch/{tid}.prompt.md", inp=pre + body)
    start = (
        f"cd ~ && echo queued > ~/.orch/{tid}.status && "
        f"if command -v tmux >/dev/null 2>&1; then "
        f"tmux kill-session -t orch-{tid} 2>/dev/null; "
        f"tmux new-session -d -s orch-{tid} 'bash -l ~/.orch/{tid}.sh'; "
        f"else nohup setsid bash -l ~/.orch/{tid}.sh >/dev/null 2>&1 < /dev/null & fi; echo started"
    )
    ssh(w, start)
    t.update(status=ACTIVE, result=None, started_at=now(), finished_at=None, stalled=False, stall_reported=False)


def qkey(worker, agent, model):
    return f"{worker}:{agent}@{model or 'default'}"


def preflight(cfg, st, w, agent, force, model=None):
    if agent not in w["agents"]:
        die(f"worker {w['name']} has no agent '{agent}' (has {w['agents']})")
    key = qkey(w["name"], agent, model)
    if key in st["exhausted"] and not force:
        die(f"{key} hit its quota at {st['exhausted'][key]}. Use a fallback model/agent from the policy, "
            f"`clear-quota`, or --force.")
    if not force:
        cap = capacity_of(cfg, st, w, probe(w))
        if cap["free"] < 1:
            print(f"NO FREE SLOT on {w['name']}: {cap['running']}/{cap['total']} running ({cap['why']}). "
                  f"Pick another worker, wait, or --force.")
            sys.exit(4)


# --------------------------------------------------------------------------- commands
def cmd_doctor(a):
    cfg = load_config()
    url = cfg.get("repo_url") or git("remote", "get-url", "origin", check=False).stdout.strip()
    ok = True
    for w in cfg["workers"]:
        pr = probe(w)
        if pr is None:
            print(f"[{w['name']}] UNREACHABLE over ssh ({w['host']})"); ok = False; continue
        errs, warns = [], []
        if "has_git" not in pr: errs.append("git missing")
        for ag in w["agents"]:
            spec = cfg["agents"].get(ag)
            binary = spec.get("binary", ag) if isinstance(spec, dict) else ag
            if spec is None: errs.append(f"agent '{ag}' not defined in config.agents")
            elif f"has_{binary}" not in pr: errs.append(f"agent binary '{binary}' not on PATH (non-login ssh shell?)")
        if "has_tmux" not in pr: warns.append("tmux missing (falls back to nohup)")
        if "has_timeout" not in pr and "has_gtimeout" not in pr: warns.append("no timeout/gtimeout: task timeout disabled")
        if "has_flock" not in pr: warns.append("no flock: parallel tasks on this worker may race on git fetch")
        r = ssh(w, f"git ls-remote --heads {shlex.quote(w.get('repo_url') or url)} >/dev/null && echo ok", check=False)
        if "ok" not in r.stdout: errs.append("cannot reach the git remote from this worker (keys/permissions?)")
        cap = capacity_of(cfg, {"tasks": {}}, w, pr)
        print(f"[{w['name']}] agents={w['agents']} slots={cap['total']} ({cap['why']}) disk={pr.get('disk_gb')}GB")
        for e in errs: print(f"   ERROR {e}")
        for e in warns: print(f"   warn  {e}")
        ok = ok and not errs
    for f in ["AGENTS.md", cfg.get("policy_file", ".config/agent-model-policy.yaml")]:
        print(f"[local] {f}: {'found' if Path(f).exists() else 'missing'}")
    print(f"[local] verify: {cfg.get('verify') or 'NOT SET (strongly recommended)'}")
    print("OK" if ok else "PROBLEMS FOUND")


def cmd_capacity(a):
    cfg = load_config()
    st = load_state() if STATE.exists() else {"tasks": {}, "exhausted": {}}
    print(f"{'WORKER':10} {'AGENTS':22} {'RUN':>3} {'FREE':>4}/{'TOT':<3} DETAIL")
    for w in cfg["workers"]:
        cap = capacity_of(cfg, st, w, probe(w))
        ex = st.get("exhausted", {})
        ags = ",".join(a_ + ("(quota)" if any(k.startswith(f"{w['name']}:{a_}@") for k in ex) else "") for a_ in w["agents"])
        print(f"{w['name']:10} {ags:22} {cap['running']:>3} {cap['free']:>4}/{cap['total']:<3} {cap['why']}"
              f"{'  strengths: ' + w['strengths'] if w.get('strengths') else ''}")


def cmd_init(a):
    cfg = load_config()
    if STATE.exists() and not a.force:
        die("state already exists (use --force to start a new feature)")
    base = a.base or cfg.get("base_branch", "main")
    fb = f"feature/{a.feature}"
    git("fetch", "origin", "--prune")
    exists = git("ls-remote", "--exit-code", "--heads", "origin", fb, check=False).returncode == 0
    if not exists:
        git("push", "origin", f"origin/{base}:refs/heads/{fb}")
    STATE_DIR.mkdir(exist_ok=True)
    excl = Path(".git/info/exclude")
    if excl.exists() and ".orch/" not in excl.read_text():
        with excl.open("a") as f:
            f.write("\n.orch/\n")
    save_state({"feature": a.feature, "base": base, "feature_branch": fb,
                "max_fix_rounds": cfg.get("max_fix_rounds", 3), "max_total_rounds": cfg.get("max_total_rounds", 5),
                "created": now(), "tasks": {}, "exhausted": {}})
    print(f"feature branch: {fb} (from {base}) {'[existing]' if exists else '[created]'}")


def cmd_local(a):
    check_id(a.task)
    st = load_state()
    t = st["tasks"].get(a.task) or new_task(st, a.task)
    t.update(worker="manager", agent="manager", kind="impl", status="manager", started_at=t["started_at"] or now())
    git("fetch", "origin")
    has_remote = git("rev-parse", "--verify", f"origin/{t['branch']}", check=False).returncode == 0
    git("checkout", "-B", t["branch"], f"origin/{t['branch']}" if has_remote else f"origin/{st['feature_branch']}")
    log_event(t, "manager-start")
    save_state(st)
    print(f"on branch {t['branch']}. Work, commit, `git push -u origin {t['branch']}`, then `orch.py accept --task {a.task}`.")


def cmd_dispatch(a):
    check_id(a.task)
    cfg, st = load_config(), load_state()
    w = get_worker(cfg, a.worker)
    agent = a.agent or w["agents"][0]
    t = st["tasks"].get(a.task)
    if t and t["status"] == ACTIVE and not a.force:
        die(f"{a.task} is still running on {t['worker']}")
    if t and t["kind"] == "qa":
        die("that id is a QA task; use `qa`")
    prev = (t["worker"], t["agent"], t["model"]) if t else (None, None, None)
    model = a.model or (prev[2] if prev[1] == agent else None)
    preflight(cfg, st, w, agent, a.force, model)
    if not t:
        t = new_task(st, a.task)
    t.update(worker=w["name"], agent=agent, model=model,
             role=a.role or t.get("role") or "implementer")
    launch(cfg, st, a.task, Path(a.prompt_file).read_text())
    log_event(t, "dispatched", worker=w["name"], agent=agent, model=t["model"], prompt=a.prompt_file,
              handoff_from=None if prev[0] in (None, w["name"]) and prev[1] in (None, agent) else f"{prev[0]}:{prev[1]}")
    save_state(st)
    print(f"{a.task} -> {w['name']}:{agent}{'@' + t['model'] if t['model'] else ''} on {t['branch']}: started")


def cmd_qa(a):
    cfg, st = load_config(), load_state()
    tgt = task_or_die(st, a.task)
    w = get_worker(cfg, a.worker)
    agent = a.agent or w["agents"][0]
    if tgt["agent"] == agent and not a.allow_self:
        die(f"'{agent}' implemented {a.task}; it is not an independent reviewer. Pick another agent "
            f"or pass --allow-self (then report the QA as NOT independent).")
    git("fetch", "origin")
    if git("rev-parse", "--verify", f"origin/{tgt['branch']}", check=False).returncode != 0:
        die(f"{tgt['branch']} is not pushed yet")
    preflight(cfg, st, w, agent, a.force, a.model)
    n = 1 + sum(1 for k in st["tasks"] if k.startswith(f"{a.task}-qa"))
    qid = f"{a.task}-qa{n}"
    check_id(qid)
    new_task(st, qid, kind="qa", worker=w["name"], agent=agent, model=a.model, role="independent_qa",
             branch=tgt["branch"], target=a.task)
    launch(cfg, st, qid, Path(a.prompt_file).read_text())
    log_event(st["tasks"][qid], "qa-dispatched", target=a.task)
    save_state(st)
    print(f"{qid}: independent QA of {a.task} -> {w['name']}:{agent}")


def remote_check(cfg, t, tid):
    w = get_worker(cfg, t["worker"])
    stall = int(cfg.get("stall_minutes", 15))
    cmd = (f"cat ~/.orch/{tid}.status 2>/dev/null || echo missing; "
           f"cat ~/.orch/{tid}.started 2>/dev/null || echo 0; "
           f"{{ find ~/.orch/{tid}.agent.log -mmin -{stall} 2>/dev/null; "
           f"find {wt_path(w, tid)} -name .git -prune -o -type f -mmin -{stall} -print 2>/dev/null | head -1; }} | wc -l")
    r = ssh(w, cmd, check=False)
    if r.returncode != 0:
        return "unreachable", 0, 1
    lines = (r.stdout.strip().splitlines() + ["", "0", "1"])[:3]
    try:
        return lines[0].strip(), int(lines[1].strip() or 0), int(lines[2].strip() or 0)
    except ValueError:
        return lines[0].strip(), 0, 1


def refresh(cfg, st):
    changed = []
    stall = int(cfg.get("stall_minutes", 15))
    for tid, t in st["tasks"].items():
        if t["status"] != ACTIVE:
            continue
        rs, started, active = remote_check(cfg, t, tid)
        t["remote"] = rs
        word = rs.split()[0] if rs else "missing"
        if word in ("done", "failed", "quota", "timeout"):
            t["status"] = "failed" if word == "failed" else ("done" if word == "done" else word)
            t["result"] = rs.split()[1] if word == "done" and len(rs.split()) > 1 else None
            t["finished_at"] = now()
            if word == "quota":
                st["exhausted"][qkey(t["worker"], t["agent"], t["model"])] = now()
            changed.append(tid)
            log_event(t, "finished", detail=rs)
        else:
            t["elapsed_min"] = int((time.time() - started) / 60) if started else None
            t["stalled"] = bool(started and active == 0 and time.time() - started > stall * 60)
            if not t["stalled"]:
                t["stall_reported"] = False
    save_state(st)
    return changed


def print_table(st):
    print(f"feature: {st['feature']}  branch: {st['feature_branch']}  base: {st['base']}")
    print(f"{'TASK':16} {'KIND':4} {'WHERE':22} {'STATUS':9} {'RES':8} {'RND':3} NOTE")
    for tid, t in st["tasks"].items():
        where = f"{t['worker']}:{t['agent']}" if t["worker"] != "manager" else "manager"
        note = []
        if t["status"] == ACTIVE and t.get("elapsed_min") is not None:
            note.append(f"{t['elapsed_min']}m")
        if t.get("stalled"):
            note.append("STALLED? check log")
        if t["issues"]:
            note.append(",".join(f"{k}:{v}" for k, v in t["issues"].items()))
        print(f"{tid:16} {t['kind']:4} {where:22} {t['status']:9} {t.get('result') or '':8} {t['rounds']:<3} {' '.join(note)}")
    if st.get("exhausted"):
        print("quota-exhausted:", ", ".join(f"{k} (since {v})" for k, v in st["exhausted"].items()))


def cmd_status(a):
    cfg, st = load_config(), load_state()
    refresh(cfg, st)
    print_table(st)


def cmd_wait(a):
    cfg, st = load_config(), load_state()
    start = time.time()
    while True:
        changed = refresh(cfg, st)
        if changed:
            print("finished:", " ".join(f"{c}({st['tasks'][c]['status']} {st['tasks'][c].get('result') or ''})".replace(" )", ")") for c in changed))
            return
        if not any(t["status"] == ACTIVE for t in st["tasks"].values()):
            print("nothing running")
            return
        stalled = [k for k, t in st["tasks"].items() if t.get("stalled") and not t.get("stall_reported")]
        if stalled:
            for k in stalled:
                st["tasks"][k]["stall_reported"] = True
            save_state(st)
            print("possibly stalled (no file activity):", ", ".join(stalled),
                  "- check `log --what agent`; wait will not report these again unless they recover and stall again")
            return
        if a.timeout and time.time() - start > a.timeout:
            print("timeout - still running")
            return
        time.sleep(a.interval)


